// Build a lookup from variant → entry (case-insensitive)
const VARIANT_INDEX = new Map<string, CityEntry>();
const CITIES: CityEntry[] = RAW.map(([canonical, country, variants]) => {
  const entry: CityEntry = { canonical, country, variants };
  for (const v of variants) {
    VARIANT_INDEX.set(v.toLowerCase(), entry);
  }
  return entry;
});

/** Универсальный словарь всех городов (по варианту → канону) */
export const ALL_CITY_VARIANTS: string[] = Array.from(VARIANT_INDEX.keys());

export function getCityEntry(variant: string): CityEntry | null {
  return VARIANT_INDEX.get(variant.toLowerCase()) ?? null;
}

export function getAllCities(): CityEntry[] {
  return CITIES;
}

